"""Service layer for the Automation Agent.

Wraps :class:`automation_agent.automation_agent.AutomationAgent` in a dict-in,
dict-out interface. The agent already separates parsing, recipient lookup, and
drafting; :meth:`AutomationAgent.execute` returns a three-tuple and
:meth:`AutomationAgent.parse_instruction` a single meeting, so both service
methods exist to translate those into the dictionary the API layer expects.

``execute`` drafts a plain-text body generated by the model. ``execute_html``
drafts the same meeting as an HTML body rendered from a shipped template. Neither sends mail.

Organization-scoped roster: the authenticated organization's active registered
employees are the single authoritative source. The ``organization_id`` and
``session`` are mandatory; there is no fallback to a packaged directory.
"""

from __future__ import annotations

import asyncio
import logging
from typing import Any

from sqlalchemy.ext.asyncio import AsyncSession

from app.core.config import get_settings
from app.core.exceptions import ValidationFailedError
from app.services.employee_directory import list_active_users_by_organization
from automation_agent.automation_agent import AutomationAgent
from automation_agent.llm.local_llm import LocalLLM
from automation_agent.rendering import DEFAULT_TEMPLATE, InvitationRenderer

logger = logging.getLogger(__name__)


async def _resolve_roster_from_organization(
    user_context: dict[str, Any],
    session: AsyncSession,
) -> list[dict[str, Any]]:
    """Resolve active registered employees from the authenticated organisation.

    Fetches the organisation's active users via the employee directory service.
    This is the only source of employees for the AutomationAgent.

    Args:
        user_context: Dict with ``user_id``, ``organization_id``, and ``role``
            from the authenticated principal.
        session: An async SQLAlchemy session for the directory query.

    Returns:
        A list of active user dicts keyed by ``id``, ``email``,
        ``full_name``, and ``role``, organised by the authenticated
        organisation.
    """
    organization_id = user_context.get("organization_id")
    if not organization_id:
        return []

    active_users = await list_active_users_by_organization(
        organization_id=organization_id,
        session=session,
    )

    # Add `name` alias for compatibility with AutomationAgent which expects `name`.
    normalized: list[dict[str, Any]] = []
    for user in active_users:
        record = dict(user)
        if "name" not in record and record.get("full_name"):
            record["name"] = record["full_name"]
        record.setdefault("is_active", True)
        normalized.append(record)
    return normalized


class AutomationService:
    """Dict-in, dict-out facade over the Automation Agent.

    The service owns no parsing or drafting logic of its own. It translates
    the agent's tuple return into the dictionary the API layer expects.

    Organization-scoped roster: the authenticated organization's active registered
    employees are the single authoritative source. The ``organization_id`` and
    ``session`` are mandatory; there is no fallback to a packaged directory.
    """

    def __init__(self, settings: Any | None = None) -> None:
        """Load the LLM client, employee directory, and HTML renderer once.

        Args:
            settings: Application settings supplying the Ollama model and base
                URL. The employee directory is the authenticated organization's
                active registered users, loaded via the employee directory service.
        """
        self._settings = get_settings() if settings is None else settings

        self._agent = AutomationAgent(
            llm=LocalLLM(
                model=self._settings.ollama_model,
                base_url=self._settings.ollama_base_url,
            ),
        )

        # Built once here rather than per request: the Jinja environment is
        # expensive enough to be worth caching and cheap enough to be worth
        # failing at startup, so a deployment without Jinja degrades to an
        # unavailable agent instead of failing on the first HTML draft.
        self._renderer = InvitationRenderer()

        logger.info(
            "automation_service_ready model=%s",
            self._settings.ollama_model,
        )

    def _filter_selected_employees(
        self,
        roster: list[dict[str, Any]],
        selected_employee_ids: list[str] | None,
    ) -> list[dict[str, Any]]:
        """Filter roster to selected employee UUIDs, validating each ID.

        Args:
            roster: The resolved organization roster.
            selected_employee_ids: Optional list of employee UUIDs to include.

        Returns:
            Filtered roster containing only selected employees.

        Raises:
            ValueError: If any selected ID is not found in the roster.
        """
        if not selected_employee_ids:
            return roster

        roster_by_id = {str(emp.get("id")): emp for emp in roster if emp.get("id")}
        selected: list[dict[str, Any]] = []
        unknown: list[str] = []
        for eid in selected_employee_ids:
            emp = roster_by_id.get(str(eid))
            if emp is None:
                unknown.append(str(eid))
            else:
                selected.append(emp)
        if unknown:
            raise ValueError(f"Unknown or inactive employee IDs: {', '.join(unknown)}")
        return selected

    def _resolve_roster(
        self,
        employees: list[dict[str, Any]] | None,
        user_context: dict[str, Any] | None,
        session: AsyncSession | None,
    ) -> list[dict[str, Any]]:
        """Resolve the employee roster using the authenticated organization.

        The authenticated organization's active registered employees are the
        single authoritative source. There is no fallback to a packaged directory.

        Organization-scoped roster enforcement:
          - If ``employees`` is supplied, use it directly after validating
            that all records belong to the authenticated organization and are active.
          - If ``user_context`` carries an ``organization_id`` and a ``session`` is
            available, resolve active registered employees from that organisation.
          - If ``user_context`` carries an ``organization_id`` but ``session`` is
            NOT provided, raise an error (session is mandatory).
          - If no ``organization_id`` exists in ``user_context``, raise an error.

        Args:
            employees: Explicit employee list from the caller (must be provided).
            user_context: Dict with ``user_id``, ``organization_id``, and ``role``
                from the authenticated principal.
            session: Async SQLAlchemy session for organisation-scoped roster resolution.
                Mandatory when ``user_context`` is provided.

        Returns:
            The employee list to use for name resolution.

        Raises:
            ValueError: If ``session`` is missing when ``organization_id`` is present,
                or if ``organization_id`` is missing from ``user_context``.
        """
        if employees is not None:
            # Explicit employee list supplied; validate organization membership and activity.
            organization_id = user_context.get("organization_id") if user_context else None
            if not organization_id:
                raise ValueError("Organization context required when employees are supplied.")
            # Validate that all employees belong to the authenticated organization
            # and are active. Each record must have 'organization_id' and 'is_active' fields.
            validated: list[dict[str, Any]] = []
            for emp in employees:
                if emp.get("organization_id") != organization_id:
                    raise ValueError(
                        f"Employee {emp.get('name', 'unknown')} does not belong "
                        f"to organization {organization_id}."
                    )
                if not emp.get("is_active", True):
                    raise ValueError(
                        f"Employee {emp.get('name', 'unknown')} is inactive and cannot be used."
                    )
                validated.append(emp)
            return validated

        # No explicit roster: must have organization context and session.
        if not user_context:
            raise ValidationFailedError(
                "Authentication and organization context are required for automation."
            )

        organization_id = user_context.get("organization_id")
        if not organization_id:
            raise ValidationFailedError("Organization ID is required in user context.")

        if session is None:
            raise ValidationFailedError(
                "Database session is required for organization-scoped roster resolution."
            )

        # Resolve active registered employees from the authenticated organisation.
        try:
            try:
                loop = asyncio.get_running_loop()
            except RuntimeError:
                loop = None

            if loop and loop.is_running():
                # Running inside an event loop (e.g. FastAPI). Use a thread to avoid
                # "cannot run loop while another loop is running".
                import concurrent.futures

                with concurrent.futures.ThreadPoolExecutor(max_workers=1) as pool:
                    roster = pool.submit(
                        asyncio.run,
                        _resolve_roster_from_organization(user_context, session),
                    ).result()
            else:
                roster = asyncio.run(_resolve_roster_from_organization(user_context, session))
            if not roster:
                raise ValueError("No active employees found in the authenticated organization.")
            return roster
        except Exception as e:
            raise ValueError(f"Failed to resolve organization employees: {e!s}") from e

    def execute(
        self,
        instruction: str,
        employees: list[dict[str, Any]] | None,
        user_context: dict[str, Any],
        session: AsyncSession,
        selected_employee_ids: list[str] | None = None,
    ) -> dict[str, Any]:
        """Turn a natural language instruction into a meeting and a draft.

        The authenticated organization's active registered employees are the
        single authoritative source for recipient resolution. There is no
        fallback to a packaged directory.

        Args:
            instruction: The instruction to act on, for example "Schedule a
                sprint planning on 5 March at 10 AM with Navneet".
            employees: Employee records to resolve names against. Must be
                provided; the packaged directory has been removed.
            user_context: Dict with ``user_id``, ``organization_id``, and
                ``role`` from the authenticated principal. Mandatory.
            session: Async SQLAlchemy session for organisation-scoped roster
                resolution. Mandatory.

        Returns:
            A dictionary with ``meeting`` holding the parsed details,
            ``recipients`` holding the matched employee records, ``email``
            holding the drafted body, and ``employee_count`` reporting how
            large the roster that was used. The draft is not sent.
        """
        roster = self._resolve_roster(employees, user_context, session)
        roster = self._filter_selected_employees(roster, selected_employee_ids)

        meeting, recipients, email = self._agent.execute(instruction, roster)

        logger.info(
            "automation_execute recipients=%d title=%s employees=%d",
            len(recipients),
            meeting.get("title", ""),
            len(roster),
        )

        return {
            "meeting": meeting,
            "recipients": recipients,
            "email": email,
            "employee_count": len(roster),
        }

    def execute_html(
        self,
        instruction: str,
        employees: list[dict[str, Any]] | None,
        user_context: dict[str, Any],
        template: str = DEFAULT_TEMPLATE,
        reason: str = "",
        session: AsyncSession | None = None,
        selected_employee_ids: list[str] | None = None,
    ) -> dict[str, Any]:
        """Turn an instruction into a meeting and an HTML email draft.

        This is the drafting half of :meth:`execute` with the body rendered
        from a shipped template instead of generated by the model. Parsing and
        recipient lookup are the agent's, so both operations resolve the same
        names against the same roster and agree on who is being invited.

        No model call happens here: the body is a pure function of the parsed
        meeting and the template, which is what makes an HTML draft cheap
        enough to offer alongside the generated one.

        The authenticated organization's active registered employees are the
        single authoritative source. There is no fallback to a packaged directory.

        Args:
            instruction: The instruction to act on, in the same form
                :meth:`execute` accepts.
            employees: Employee records to resolve names against. Must be
                provided; the packaged directory has been removed.
            user_context: Dict with ``user_id``, ``organization_id``, and
                ``role`` from the authenticated principal. Mandatory.
            template: Which shipped template to render. A blank value selects
                the default invitation template.
            reason: Optional purpose line printed with the meeting details. A
                blank value omits the line rather than printing an empty one.
            session: Async SQLAlchemy session for organisation-scoped
                roster resolution. Mandatory when ``user_context`` is provided.

        Returns:
            A dictionary with ``meeting`` holding the parsed details,
            ``recipients`` holding the matched employee records, ``subject``
            and ``html_body`` holding the rendered draft, ``template`` naming
            the template that was used, and ``employee_count`` reporting how
            large the roster in use was. The draft is not sent.

        Raises:
            ValueError: If ``template`` is not one of the shipped templates.
        """
        roster = self._resolve_roster(employees, user_context, session)
        roster = self._filter_selected_employees(roster, selected_employee_ids)

        meeting = self._agent.parse_instruction(instruction, roster)

        recipients = self._agent.find_emails(meeting["attendees"], roster)

        chosen = str(template or "").strip() or DEFAULT_TEMPLATE

        rendered = self._renderer.render(
            meeting,
            recipients,
            template=chosen,
            reason=reason,
        )

        logger.info(
            "automation_execute_html recipients=%d title=%s template=%s employees=%d",
            len(recipients),
            meeting.get("title", ""),
            chosen,
            len(roster),
        )

        return {
            "meeting": meeting,
            "recipients": recipients,
            "subject": rendered["subject"],
            "html_body": rendered["html_body"],
            "template": chosen,
            "employee_count": len(roster),
        }
